import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import type { JSONReport, JSONReportSuite } from '@playwright/test/reporter';

import { playwrightCli, runNodeScript } from '../core/services/process.util.js';
import { ensureDir } from '../utils/file.util.js';
import { isPathInside, paths } from '../utils/paths.js';
import { isScriptPayload, type SecretRedactor } from '../console/input-guard.js';
import { maskSensitiveText, stripAnsi, truncate } from '../utils/sanitizer.js';
import type { AgentEvent, AgentTool } from './types.js';

export const GENERATED_CONFIG = 'playwright.generated.config.ts';
const FILE_NAME = /^[a-z0-9][a-z0-9-]{0,60}\.spec\.ts$/;
const MAX_RUNS = 6;

const DRAFT_HEADER = `/**
 * GENERATED BY THE TEST CONSOLE – REVIEW BEFORE USE.
 * Run: CONSOLE_BASE_URL=<url> npx playwright test -c ${GENERATED_CONFIG} <this file>
 */
`;

/**
 * Static safety checks for model-written test code before it is saved and executed.
 * Generated tests may only import @playwright/test and must not touch the process,
 * filesystem, network modules or dynamic code evaluation. This is a guard-rail
 * against prompt injection from page content – not a sandbox.
 */
export function validateGeneratedTestCode(code: string, targetUrl?: string): string[] {
  const problems: string[] = [];
  if (code.length > 60_000) problems.push('file is larger than 60 000 characters');
  // Hidden characters could disguise code from the human reviewer.
  if (/[\u200B-\u200F\u202A-\u202E\u2060-\u2064\uFEFF]/.test(code))
    problems.push('invisible/bidi Unicode characters are not allowed');
  const imports = [...code.matchAll(/^\s*(?:import|export)\s[^;]*?from\s+['"]([^'"]+)['"]/gm)].map(
    (m) => m[1],
  );
  for (const source of imports) {
    if (source !== '@playwright/test')
      problems.push(`import from "${source}" is not allowed (only @playwright/test)`);
  }
  const forbidden: Array<[RegExp, string]> = [
    [/\brequire\s*\(/, 'require()'],
    [/\bimport\s*\(/, 'dynamic import()'],
    [/\bimport\s+['"]/, 'side-effect imports'],
    [/\bprocess\s*[.[]/, 'process access'],
    [/\b(eval|Function)\s*\(|\bsetTimeout\s*\(\s*['"`]/, 'dynamic code evaluation'],
    [/child_process|node:|\bglobalThis\b|__dirname|__filename|\bBuffer\b/, 'Node.js internals'],
    [/\b(fetch|XMLHttpRequest|WebSocket|EventSource)\b/, 'direct network access'],
    [
      /\.\s*(evaluate|evaluateHandle|evaluateAll|\$eval|\$\$eval|addInitScript|addScriptTag|addStyleTag|exposeFunction|exposeBinding)\s*\(/,
      'injecting code into the page',
    ],
    [
      /\.\s*(route|routeFromHAR|routeWebSocket|setExtraHTTPHeaders|setHTTPCredentials|grantPermissions)\s*\(/,
      'network interception or credential/permission changes',
    ],
    [
      /\b(request|playwright|browserType|chromium|firefox|webkit)\s*\.\s*(newContext|launch|connect|get|post|put|patch|delete|fetch)\s*\(/,
      'additional browsers or API request contexts',
    ],
    [/\.\s*(setInputFiles|saveAs|storageState)\s*\(|\bpath\s*:\s*['"`]/, 'file system access'],
    [/waitForTimeout\s*\(/, 'fixed sleeps (use web-first assertions)'],
  ];
  for (const [pattern, label] of forbidden) if (pattern.test(code)) problems.push(`${label} is not allowed`);

  // Absolute URLs must stay on the target site (relative page.goto('/…') is preferred).
  if (targetUrl) {
    const origin = new URL(targetUrl).origin;
    for (const match of code.matchAll(/\b[a-z][a-z0-9+.-]*:\/\/[^\s'"`)]+/gi)) {
      let other: string | undefined;
      try {
        other = new URL(match[0]).origin === origin ? undefined : match[0];
      } catch {
        other = match[0];
      }
      if (other) problems.push(`URL ${other} is outside the target site ${origin}`);
    }
  }
  if (isScriptPayload(code.replace(/<\/?\s*(main|header|nav)\b/gi, '')))
    problems.push('script/markup payloads are not allowed');
  if (!/\btest\s*\(/.test(code)) problems.push('no test(...) found');
  return [...new Set(problems)];
}

interface DraftToolsOptions {
  runId: string;
  baseUrl: string;
  /** Whether run_test_file is offered to the model. */
  allowRun: boolean;
  emit: (event: AgentEvent) => void;
  /** Maps an absolute artifact path to a URL served by the console. */
  urlFor: (absolutePath: string) => string;
  /** Rejects code that contains configured secret values. */
  redactor?: SecretRedactor;
}

/** Tools for writing test drafts to generated-tests/ and running them in isolation. */
export function createDraftTools(options: DraftToolsOptions): AgentTool[] {
  const draftsDir = path.join(paths.generatedTests, 'console', options.runId);
  const runsDir = path.join(paths.reports, 'console-runs', options.runId, 'test-runs');
  let runs = 0;

  const resolveDraft = (fileName: unknown): string | { error: string } => {
    if (typeof fileName !== 'string' || !FILE_NAME.test(fileName)) {
      return { error: 'fileName must look like "login-smoke.spec.ts" (lowercase, digits, dashes)' };
    }
    const file = path.join(draftsDir, fileName);
    return isPathInside(draftsDir, file) ? file : { error: 'invalid file name' };
  };

  const save: AgentTool = {
    spec: {
      name: 'save_test_file',
      description:
        'Save a Playwright test file (TypeScript) to the review folder generated-tests/. ' +
        "Import only from '@playwright/test'. Use relative URLs with page.goto('/...') – baseURL is the target site. " +
        'Overwrites a file of the same name in this run.',
      parameters: {
        type: 'object',
        properties: {
          fileName: { type: 'string', description: 'e.g. "home-smoke.spec.ts"' },
          code: { type: 'string', description: 'Complete file content' },
        },
        required: ['fileName', 'code'],
        additionalProperties: false,
      },
    },
    execute: (args) => {
      const file = resolveDraft(args.fileName);
      if (typeof file !== 'string') return Promise.resolve({ text: `ERROR: ${file.error}`, isError: true });
      if (typeof args.code !== 'string')
        return Promise.resolve({ text: 'ERROR: code must be a string', isError: true });
      const problems = validateGeneratedTestCode(args.code, options.baseUrl);
      if (options.redactor?.contains(args.code)) problems.push('code contains a configured secret value');
      if (problems.length > 0) {
        return Promise.resolve({ text: `ERROR: code rejected:\n- ${problems.join('\n- ')}`, isError: true });
      }
      ensureDir(draftsDir);
      writeFileSync(file, args.code.startsWith('/**') ? args.code : DRAFT_HEADER + args.code, 'utf8');
      const relative = path.relative(paths.root, file).split(path.sep).join('/');
      options.emit({ type: 'file', kind: 'test', name: relative, url: options.urlFor(file) });
      return Promise.resolve({ text: `Saved ${relative}` });
    },
  };

  const run: AgentTool = {
    spec: {
      name: 'run_test_file',
      description:
        'Run a previously saved test file headlessly in Chromium against the target site and return the results ' +
        `(max ${MAX_RUNS} runs per session). Fix genuine test-code mistakes and re-run; report real application defects instead of hiding them.`,
      parameters: {
        type: 'object',
        properties: { fileName: { type: 'string' } },
        required: ['fileName'],
        additionalProperties: false,
      },
    },
    execute: async (args, signal) => {
      const file = resolveDraft(args.fileName);
      if (typeof file !== 'string') return { text: `ERROR: ${file.error}`, isError: true };
      if (!existsSync(file))
        return { text: `ERROR: ${String(args.fileName)} has not been saved yet`, isError: true };
      if (++runs > MAX_RUNS) return { text: `ERROR: run limit (${MAX_RUNS}) reached`, isError: true };

      const reportDir = path.join(runsDir, `run-${runs}`);
      const result = await runNodeScript(
        playwrightCli(),
        ['test', '-c', GENERATED_CONFIG, path.relative(paths.root, file).split(path.sep).join('/')],
        {
          cwd: paths.root,
          timeoutMs: 300_000,
          signal,
          env: { ...process.env, CONSOLE_BASE_URL: options.baseUrl, REPORT_DIR: reportDir, FORCE_COLOR: '0' },
        },
      );
      const summary = summarizeReport(path.join(reportDir, 'results.json'));
      const htmlReport = path.join(reportDir, 'html', 'index.html');
      options.emit({
        type: 'test_run',
        fileName: String(args.fileName),
        status: result.timedOut
          ? 'timedout'
          : summary
            ? summary.totals.failed > 0
              ? 'failed'
              : 'passed'
            : 'error',
        totals: { ...(summary?.totals ?? {}) },
        ...(existsSync(htmlReport) ? { reportUrl: options.urlFor(htmlReport) } : {}),
      });
      if (!summary) {
        return {
          text: `ERROR: test run produced no results (exit ${result.exitCode}).\n${truncate(stripAnsi(result.output.slice(-3000)), 3000)}`,
          isError: true,
        };
      }
      return { text: summary.text, isError: summary.totals.failed > 0 };
    },
  };

  return options.allowRun ? [save, run] : [save];
}

/** Compact, model-friendly summary of a Playwright JSON report. */
export interface RunTotals {
  passed: number;
  failed: number;
  skipped: number;
  flaky: number;
}

export function summarizeReport(file: string): { totals: RunTotals; text: string } | undefined {
  if (!existsSync(file)) return undefined;
  const report = JSON.parse(readFileSync(file, 'utf8')) as JSONReport;
  const lines: string[] = [];
  const totals: RunTotals = { passed: 0, failed: 0, skipped: 0, flaky: 0 };
  const visit = (suite: JSONReportSuite, prefix: string[]) => {
    const title = suite.title && !suite.title.endsWith('.ts') ? [...prefix, suite.title] : prefix;
    for (const spec of suite.specs) {
      for (const test of spec.tests) {
        const last = test.results.at(-1);
        const outcome: keyof RunTotals =
          test.status === 'expected' ? 'passed' : test.status === 'unexpected' ? 'failed' : test.status;
        totals[outcome] += 1;
        const error = last?.errors[0]?.message;
        lines.push(
          `${outcome.toUpperCase()}: ${[...title, spec.title].join(' > ')} (${last?.duration ?? 0}ms)` +
            (error
              ? `\n  ${truncate(maskSensitiveText(stripAnsi(error)).split('\n').slice(0, 8).join('\n  '), 1200)}`
              : ''),
        );
      }
    }
    for (const child of suite.suites ?? []) visit(child, title);
  };
  for (const suite of report.suites) visit(suite, []);
  return {
    totals,
    text: `Totals: ${totals.passed} passed, ${totals.failed} failed, ${totals.skipped} skipped, ${totals.flaky} flaky\n${lines.join('\n')}`,
  };
}
