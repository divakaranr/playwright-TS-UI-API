import { z } from 'zod';

import type { FetchLike } from '../ai/providers/http-transport.js';
import { createToolChatClient, type ToolCallingProvider } from '../ai/providers/tool-chat.js';
import { validateGeneratedTestCode } from '../agent/code-validator.js';
import { buildSystemPrompt, buildUserMessage } from '../agent/prompts.js';
import { TestAgent } from '../agent/test-agent.js';
import type { AgentEvent, AgentRunStatus, AgentTool } from '../agent/types.js';
import { SecretRedactor } from '../console/input-guard.js';
import { BrowserSession, type BrowserLauncher } from './browser-tools.js';

/** Providers offered by the hosted app (a local Ollama is not reachable from the cloud). */
export const WEB_PROVIDERS = [
  'openrouter',
  'openai',
  'anthropic',
] as const satisfies readonly ToolCallingProvider[];

/** Events streamed to the browser as NDJSON. */
export type WebEvent =
  | Exclude<AgentEvent, { type: 'screenshot' | 'file' | 'test_run' }>
  | { type: 'screenshot'; caption: string; dataUrl: string }
  | { type: 'file'; name: string; code: string };

export interface WebRunRequest {
  targetUrl: string;
  prompt: string;
  mode: 'explore' | 'generate';
  maxSteps: number;
  provider: (typeof WEB_PROVIDERS)[number];
  model: string;
  apiKey: string;
}

export interface WebRunDeps {
  launch: BrowserLauncher;
  emit: (event: WebEvent) => void;
  signal: AbortSignal;
  /** Soft budget: afterwards tools refuse and the model must write its report (default 200 s). */
  softBudgetMs?: number;
  /** Hard stop (default 270 s – Vercel functions end at 300 s). */
  hardBudgetMs?: number;
  allowPrivateNetwork?: boolean;
  baseUrls?: Partial<Record<ToolCallingProvider, string>>;
  fetch?: FetchLike;
}

const FILE_NAME = /^[a-z0-9][a-z0-9-]{0,60}\.spec\.ts$/;
const MAX_FILES = 10;
const MAX_SCREENSHOTS = 12;

export const GENERATED_HEADER = (targetUrl: string) => `/**
 * GENERATED BY THE PLAYWRIGHT TEST CONSOLE – REVIEW BEFORE USE.
 * Target: ${new URL(targetUrl).origin}
 * Run:    npm install && npx playwright install chromium && npx playwright test
 */
`;

const saveSchema = z.object({ fileName: z.string(), code: z.string().max(60_000) }).strict();

function draftTools(
  targetUrl: string,
  redactor: SecretRedactor,
  emit: (event: WebEvent) => void,
): AgentTool[] {
  const saved = new Map<string, string>();
  return [
    {
      spec: {
        name: 'save_test_file',
        description:
          'Save a Playwright test file for the user to download. fileName: kebab-case ending in .spec.ts. ' +
          'Saving the same name again replaces the file. The file is validated before it is accepted.',
        parameters: {
          type: 'object',
          properties: { fileName: { type: 'string' }, code: { type: 'string' } },
          required: ['fileName', 'code'],
          additionalProperties: false,
        },
      },
      execute: (raw) => {
        const parsed = saveSchema.safeParse(raw);
        if (!parsed.success)
          return Promise.resolve({
            text: 'Invalid arguments: fileName and code are required',
            isError: true,
          });
        const { fileName, code } = parsed.data;
        if (!FILE_NAME.test(fileName))
          return Promise.resolve({
            text: 'fileName must be kebab-case and end with .spec.ts',
            isError: true,
          });
        if (!saved.has(fileName) && saved.size >= MAX_FILES)
          return Promise.resolve({ text: `At most ${MAX_FILES} files per run`, isError: true });
        const problems = validateGeneratedTestCode(code, targetUrl);
        if (redactor.contains(code)) problems.push('the code contains a secret value');
        if (problems.length > 0)
          return Promise.resolve({
            text: `File rejected:\n- ${problems.join('\n- ')}\nFix the code and save again.`,
            isError: true,
          });
        const content = GENERATED_HEADER(targetUrl) + code.trimStart();
        saved.set(fileName, content);
        emit({ type: 'file', name: fileName, code: content });
        return Promise.resolve({
          text: `Saved ${fileName} (${content.length} characters). The user can download it.`,
        });
      },
    },
  ];
}

/** Executes one hosted run end-to-end and emits its events; never throws. */
export async function executeWebRun(request: WebRunRequest, deps: WebRunDeps): Promise<AgentRunStatus> {
  const started = Date.now();
  const redactor = new SecretRedactor({ ...process.env, USER_LLM_API_KEY: request.apiKey });
  const emit = (event: WebEvent) => deps.emit(redactor.redactValue(event));
  const hard = new AbortController();
  const onAbort = () => hard.abort();
  deps.signal.addEventListener('abort', onAbort);
  const hardTimer = setTimeout(() => hard.abort(), deps.hardBudgetMs ?? 270_000);
  const softDeadline = started + (deps.softBudgetMs ?? 200_000);

  let status: AgentRunStatus = 'failed';
  let report: string;
  let steps = 0;
  let browser: Awaited<ReturnType<BrowserLauncher>> | undefined;
  try {
    emit({ type: 'status', message: 'Starting browser…' });
    browser = await deps.launch();
    const session = new BrowserSession(browser, {
      targetUrl: request.targetUrl,
      ...(deps.allowPrivateNetwork ? { allowPrivateNetwork: true } : {}),
    });
    await session.open();

    let shots = 0;
    const onVisual = async (caption: string) => {
      if (shots >= MAX_SCREENSHOTS) return;
      shots += 1;
      const dataUrl = await session.screenshot().catch(() => undefined);
      if (dataUrl) emit({ type: 'screenshot', caption, dataUrl });
    };
    const budgeted = (tool: AgentTool): AgentTool => ({
      spec: tool.spec,
      execute: (args, signal) =>
        Date.now() > softDeadline
          ? Promise.resolve({
              text: 'TIME BUDGET EXHAUSTED: do not call more tools. Write the final report now.',
              isError: true,
            })
          : tool.execute(args, signal),
    });
    const tools = [
      ...session.tools(onVisual),
      ...(request.mode === 'generate' ? draftTools(request.targetUrl, redactor, emit) : []),
    ].map(budgeted);

    const chat = createToolChatClient(
      {
        provider: request.provider,
        model: request.model,
        apiKey: request.apiKey,
        baseUrl: deps.baseUrls?.[request.provider],
        timeoutMs: 90_000,
        maxRetries: 1,
      },
      deps.fetch ? { fetch: deps.fetch } : {},
    );
    emit({ type: 'status', message: `Agent started · ${request.provider} · ${request.model}` });
    // The agent loop itself never emits screenshot/file/test_run events (those come from the tools above).
    const agent = new TestAgent({
      chat,
      tools,
      emit: (event) => emit(event as WebEvent),
      maxSteps: request.maxSteps,
      signal: hard.signal,
    });
    const result = await agent.run(
      buildSystemPrompt(request.mode, request.targetUrl, false),
      buildUserMessage(request.targetUrl, request.prompt),
    );
    status = result.status;
    steps = result.steps;
    report = redactor.redact(result.report);
    if (status === 'cancelled' && !deps.signal.aborted)
      report = `The run reached the time limit of this hosted version. Files saved so far are available.\n\n${report}`;
  } catch (error) {
    report = `Run failed: ${redactor.redact((error as Error).message)}`;
    emit({ type: 'error', message: (error as Error).message });
  } finally {
    clearTimeout(hardTimer);
    deps.signal.removeEventListener('abort', onAbort);
    await browser?.close().catch(() => undefined);
  }
  emit({ type: 'report', markdown: report });
  emit({ type: 'done', status, durationMs: Date.now() - started, steps });
  return status;
}
